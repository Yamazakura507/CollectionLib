namespace CollectionLib.Enums;

/// <summary>
/// Defines how grouped items are arranged and visually connected in a collection list.
/// </summary>
public enum CollectionGroupDisplayMode
{
    /// <summary>
    /// Groups are displayed as filled blocks with collapsible headers.
    /// </summary>
    Blocks,

    /// <summary>
    /// Groups are displayed as a connected tree with thin guide lines.
    /// </summary>
    Lines
}
