namespace CollectionLib.Enums;

/// <summary>
/// Selects the visual transition used when a collection-list search panel appears or disappears.
/// </summary>
public enum CollectionSearchEffect
{
    /// <summary>
    /// Fades the search panel in or out.
    /// </summary>
    Fade,

    /// <summary>
    /// Moves the search panel into or out of view.
    /// </summary>
    Slide,

    /// <summary>
    /// Scales the search panel into or out of view.
    /// </summary>
    Scale
}
